CREATE OR REPLACE NONEDITIONABLE TRIGGER TR_RESERVA_BIU
BEFORE INSERT OR UPDATE ON RESERVA
FOR EACH ROW
DECLARE
  v_duracion  SERVICIO.DURACION_MIN%TYPE;
BEGIN
  IF :NEW.SERVICIO_ID IS NOT NULL THEN
    SELECT DURACION_MIN
      INTO v_duracion
      FROM SERVICIO
     WHERE ID = :NEW.SERVICIO_ID;

    IF :NEW.HORA_FIN IS NULL
       OR INSERTING
       OR UPDATING('SERVICIO_ID')
       OR UPDATING('HORA_INICIO')
    THEN
      :NEW.HORA_FIN :=
        TO_CHAR(
          TO_DATE(:NEW.HORA_INICIO, 'HH24:MI')
          + NUMTODSINTERVAL(v_duracion, 'MINUTE'),
          'HH24:MI'
        );
    END IF;
  END IF;

  IF TO_DATE(:NEW.HORA_INICIO, 'HH24:MI')
     >= TO_DATE(:NEW.HORA_FIN, 'HH24:MI')
  THEN
    RAISE_APPLICATION_ERROR(-20000,
      'HORA_INICIO debe ser menor que HORA_FIN.');
  END IF;
END;
