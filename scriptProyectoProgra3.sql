prompt Creando trigger TR_RESERVA_BIU (validación de reservas)...
CREATE OR REPLACE TRIGGER TR_RESERVA_BIU
BEFORE INSERT OR UPDATE ON RESERVA
FOR EACH ROW
DECLARE
  v_count NUMBER;
BEGIN
  IF :NEW.HORA_FIN IS NULL THEN
    SELECT TO_CHAR(
             TO_DATE(:NEW.HORA_INICIO,'HH24:MI') +
             (duracion_min / (24*60)),
             'HH24:MI'
           )
    INTO :NEW.HORA_FIN
    FROM SERVICIO
    WHERE id = :NEW.SERVICIO_ID;
  END IF;

  SELECT COUNT(*)
  INTO v_count
  FROM RESERVA r
  WHERE r.MEDICO_ID = :NEW.MEDICO_ID
    AND r.FECHA     = :NEW.FECHA
    AND r.ID        <> NVL(:NEW.ID,-1)
    AND r.ESTADO   <> 'CANCELADA'
    AND TO_DATE(r.HORA_INICIO,'HH24:MI') < TO_DATE(:NEW.HORA_FIN,'HH24:MI')
    AND TO_DATE(:NEW.HORA_INICIO,'HH24:MI') < TO_DATE(r.HORA_FIN,'HH24:MI');

  IF v_count > 0 THEN
    RAISE_APPLICATION_ERROR(
      -20001,
      'Traslape de reserva para el médico en ese horario.'
    );
  END IF;
END;
